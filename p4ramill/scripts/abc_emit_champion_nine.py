#!/usr/bin/env python3
"""Emit exact champion comparisons through c=9 using rational log bounds."""
from fractions import Fraction
from math import gcd
from pathlib import Path
from tempfile import TemporaryDirectory
from abc_emit_window_certificate import emit, radical


def main():
    output = Path(__file__).resolve().parents[1] / 'Imscribing/ABC_ChampionNineBounds.lean'
    with TemporaryDirectory() as temp:
        raw = Path(temp) / 'window.lean'
        emit(9, Fraction(1, 10), 6, 3, raw)
        prelude = raw.read_text().split('theorem certified_upper')[0]
    prelude = prelude.replace('Window9E1_10', 'ChampionNineBounds').replace(
        'Generated by scripts/abc_emit_window_certificate.py; all claims checked by Lean.',
        'Generated by scripts/abc_emit_champion_nine.py. Exact comparisons checked by Lean.')
    lines = [prelude]
    for cutoff, winner in [(8, (1, 1)), (9, (1, 8))]:
        wa, wb = winner
        pairs = [(a, c-a) for c in range(2, cutoff+1)
                 for a in range(1, c//2+1) if gcd(a, c-a) == 1]
        for a, b in pairs:
            name = f'below_{cutoff}_{a}_{b}'
            lines += [f'private theorem {name} : discrepancy (1/10) sample_{a}_{b} ≤',
                      f'    discrepancy (1/10) sample_{wa}_{wb} := by']
            if (a, b) == winner:
                lines += ['  exact le_rfl']
            else:
                lines += [f'  have h := sample_{a}_{b}_interval.2',
                          f'  have w := sample_{wa}_{wb}_interval.1',
                          f'  norm_num [logCertificate_{a+b}, logCertificate_{radical(a*b*(a+b))}] at h',
                          f'  norm_num [logCertificate_{wa+wb}, logCertificate_{radical(wa*wb*(wa+wb))}] at w',
                          '  linarith']
        target = 'baseTriple' if cutoff == 8 else 'one_eight_nine'
        lines += [f'theorem upper_{cutoff} (t : Triple) (hc : t.c ≤ {cutoff}) :',
                  f'    discrepancy (1/10) t ≤ discrepancy (1/10) {target} := by',
                  f'  apply window_upper_of_ordered (1/10) _ {cutoff} ?_ t hc',
                  '  intro t hc hab', '  rcases t with ⟨a, b, c, ha, hb, hs, hcop⟩',
                  '  dsimp only at hc hab', '  subst c',
                  f'  have haB : a < {cutoff} := by omega',
                  f'  have hbB : b < {cutoff} := by omega',
                  f'  have cover : ∀ a b : Fin {cutoff}, 0 < a.val → 0 < b.val → a.val ≤ b.val →',
                  f'      a.val + b.val ≤ {cutoff} → Nat.Coprime a.val b.val →',
                  '      ' + ' ∨ '.join(f'(a.val = {a} ∧ b.val = {b})' for a, b in pairs) + ' := by decide',
                  '  have cases_all := cover ⟨a, haB⟩ ⟨b, hbB⟩ ha hb hab hc hcop',
                  '  rcases cases_all with ' + ' | '.join('h' for _ in pairs)]
        for a, b in pairs:
            lines += ['  · rcases h with ⟨h1, h2⟩', '    dsimp only at h1 h2',
                      '    subst a', '    subst b', f'    exact below_{cutoff}_{a}_{b}']
    lines += ['theorem strict_displacement : discrepancy (1/10) baseTriple <',
              '    discrepancy (1/10) one_eight_nine := by',
              '  have h := sample_1_1_interval.2', '  have w := sample_1_8_interval.1',
              '  norm_num [logCertificate_2] at h',
              '  norm_num [logCertificate_9, logCertificate_6] at w',
              '  change discrepancy (1/10) sample_1_1 < discrepancy (1/10) sample_1_8',
              '  linarith', 'end Imscribing.ABC.ChampionNineBounds', '']
    output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
